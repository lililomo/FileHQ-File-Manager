import type * as Monaco from 'monaco-editor'

/** Monarch grammar for Makefiles (not bundled with Monaco 0.57). */
export const makefileLanguage: Monaco.languages.IMonarchLanguage = {
  defaultToken: '',
  tokenPostfix: '.makefile',
  keywords: [
    'ifeq',
    'ifneq',
    'ifdef',
    'ifndef',
    'else',
    'endif',
    'include',
    '-include',
    'define',
    'endef',
    'export',
    'unexport',
    'override',
    'vpath',
  ],
  functions: [
    'subst',
    'patsubst',
    'strip',
    'findstring',
    'filter',
    'filter-out',
    'sort',
    'word',
    'words',
    'wordlist',
    'firstword',
    'lastword',
    'dir',
    'notdir',
    'suffix',
    'basename',
    'addsuffix',
    'addprefix',
    'join',
    'wildcard',
    'realpath',
    'abspath',
    'if',
    'or',
    'and',
    'foreach',
    'call',
    'value',
    'eval',
    'origin',
    'flavor',
    'shell',
    'error',
    'warning',
    'info',
  ],
  tokenizer: {
    root: [
      [/#.*$/, 'comment'],
      [/^\t.*$/, 'string.recipe'],
      [/^\.PHONY\b/, 'keyword'],
      [/^[A-Za-z_][\w\-.%/]*(?=\s*[:+?!]?=)/, 'variable'],
      [/^[^\s:=#][^:=#]*(?=:)/, 'type.identifier'],
      [
        /\$\(([A-Za-z_][\w-]*)/,
        { cases: { '$1@functions': 'keyword.function', '@default': 'variable' } },
      ],
      [/\$\{[^}]*\}/, 'variable'],
      [/\$[@<^*?%+|]/, 'variable.predefined'],
      [
        /\b(ifeq|ifneq|ifdef|ifndef|else|endif|include|define|endef|export|unexport|override|vpath)\b/,
        'keyword',
      ],
      [/[:+?!]?=/, 'operator'],
      [/[()]/, 'delimiter.parenthesis'],
    ],
  },
}

export const makefileConfiguration: Monaco.languages.LanguageConfiguration = {
  comments: { lineComment: '#' },
  brackets: [
    ['(', ')'],
    ['{', '}'],
  ],
}
